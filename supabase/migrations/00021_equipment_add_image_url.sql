-- =====================================================================
-- equipment 에 "썸네일 이미지 URL(image_url)" 컬럼을 추가한다.
--
-- 이미지 파일 자체를 다운로드/저장하지 않고 퐁당닷컴 상품 이미지의 링크
-- 주소만 저장한다(DB 용량 최소화). 장비 검색 목록/장바구니 UI에서 품목명
-- 왼쪽에 작은 썸네일로 표시하는 용도이며, 값이 없거나 로드에 실패하면
-- 화면에서 기본 아이콘으로 대체한다.
-- =====================================================================

alter table public.equipment
  add column if not exists image_url text;

comment on column public.equipment.image_url is
  '상품 썸네일 이미지 URL(외부 링크, 파일 자체는 저장하지 않음). 퐁당닷컴 동기화 시 함께 수집되며, 수동 등록 품목은 비어있을 수 있다.';

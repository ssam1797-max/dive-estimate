-- =====================================================================
-- equipment에 "상세페이지 옵션을 마지막으로 확인(보완 시도)한 시각"
-- 컬럼을 추가한다.
--
-- 퐁당닷컴 동기화는 조각(chunk) 1번당 상세페이지 보완을 최대 10건으로
-- 제한하는데, 지금까지는 "그 조각에서 가장 먼저 발견되는 10건"을 그대로
-- 골라왔다. 목록 페이지의 크롤링 순서가 날마다 거의 그대로라, 매일
-- 똑같은 10건만 반복 보완되고 나머지는 영원히 차례가 오지 않는 문제가
-- 있었다(실측으로 확인됨).
--
-- option_checked_at이 null이거나 가장 오래된 품목부터 우선 보완 대상으로
-- 고르도록(lib/db/equipment-repo.ts selectEnrichmentCandidates 참고)
-- 바꿔, 날마다 다른 품목이 돌아가며 보완되고 결국 전수 보완에 도달하게
-- 한다. 보완을 "시도"하기만 해도(결과적으로 옵션이 그대로여도) 이 값을
-- 갱신해 순서를 뒤로 보낸다.
-- =====================================================================

alter table public.equipment
  add column if not exists option_checked_at timestamptz;

comment on column public.equipment.option_checked_at is
  '퐁당닷컴 상세페이지에서 옵션(색상/사이즈) 목록을 마지막으로 확인(보완 시도)한 시각. null이면 한 번도 확인된 적 없음 — 동기화 시 이 값이 없거나 가장 오래된 품목을 우선 보완 대상으로 고른다.';

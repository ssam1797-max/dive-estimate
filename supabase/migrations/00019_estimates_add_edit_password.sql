-- =====================================================================
-- 견적서 수정/삭제 보호용 비밀번호 컬럼 추가
-- 작성 시 입력받은 4~6자리 숫자 비밀번호를 솔트 포함 해시("salt:hash" 형식)로
-- 저장한다. NULL이면 이 기능 추가 이전에 저장된 견적서라 비밀번호가 없다 —
-- 이 경우 대조할 비밀번호 자체가 없으므로 관리자 모드(ADMIN_PASSWORD)에서만
-- 수정/삭제할 수 있다(일반 사용자는 열람만 가능). 비밀번호가 있는 견적서는
-- 그 비밀번호를 입력해야 수정/삭제되고, 관리자 모드는 이 값과 무관하게
-- 항상 수정/삭제 가능하다. 템플릿 행에는 이 컬럼을 쓰지 않는다.
-- =====================================================================

alter table public.estimates
  add column if not exists edit_password_hash text;

comment on column public.estimates.edit_password_hash is
  '견적서 수정/삭제 보호용 비밀번호 해시(salt:hash 형식, scrypt). NULL이면(이 컬럼 추가 이전에 저장된 견적서) 관리자 모드에서만 수정/삭제 가능. 관리자 모드는 이 값과 무관하게 항상 수정/삭제 가능.';

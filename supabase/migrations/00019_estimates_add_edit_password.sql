-- =====================================================================
-- 견적서 수정/삭제 보호용 비밀번호 컬럼 추가
-- 작성 시 입력받은 4~6자리 숫자 비밀번호를 솔트 포함 해시("salt:hash" 형식)로
-- 저장한다. NULL이면 이 기능 추가 이전에 저장된 견적서라 비밀번호 보호가
-- 없다(기존 견적서는 계속 자유롭게 수정/삭제 가능 — 소급 적용하지 않음).
-- 관리자 모드(ADMIN_PASSWORD)는 이 값과 무관하게 항상 수정/삭제 가능하므로
-- 템플릿 행에는 이 컬럼을 쓰지 않는다.
-- =====================================================================

alter table public.estimates
  add column if not exists edit_password_hash text;

comment on column public.estimates.edit_password_hash is
  '견적서 수정/삭제 보호용 비밀번호 해시(salt:hash 형식, scrypt). 작성 시 설정, 관리자 모드는 이 값과 무관하게 항상 수정/삭제 가능. NULL이면 비밀번호 보호 없음(이 컬럼 추가 이전에 저장된 견적서).';
